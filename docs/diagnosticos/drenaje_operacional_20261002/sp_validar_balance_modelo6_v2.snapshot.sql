    @fecha_inicio=@inicio,@fecha_fin=@fin,@caso_id=@caso_id,@debug=0;
IF (SELECT COUNT(*) FROM #validacion_m6_actual)<>122 OR (SELECT COUNT(*) FROM #validacion_m6_nuevo)<>122
 OR EXISTS(SELECT Flujo FROM #validacion_m6_actual GROUP BY Flujo HAVING COUNT(*)>1)
 OR EXISTS(SELECT Flujo FROM #validacion_m6_nuevo GROUP BY Flujo HAVING COUNT(*)>1)
    THROW 51031, 'La comparación requiere 122 códigos únicos en ambos SP.', 1;
-- Primera comparación: refactorización contra cálculo actual con el mismo caso.
-- Segunda comparación: SP nuevo contra descarga, que también detecta cambios en fuentes/manuales.
;WITH comparaciones AS (
    SELECT 'Actual vs nuevo' comparacion,COALESCE(a.Flujo,n.Flujo) Flujo,
        a.Flujo presente_base,n.Flujo presente_nuevo,v.campo,v.base,v.nuevo
    FROM #validacion_m6_actual a FULL JOIN #validacion_m6_nuevo n ON n.Flujo=a.Flujo
    CROSS APPLY (VALUES ('TMS_Inicial',a.TMS_Inicial,n.TMS_Inicial),('Ley_Cu_1',a.Ley_Cu_1,n.Ley_Cu_1),
        ('TMS_Final',a.TMS_Final,n.TMS_Final),('Ley_Cu_2',a.Ley_Cu_2,n.Ley_Cu_2),
        ('Tonelaje',a.Tonelaje,n.Tonelaje),('Ley_Cu',a.Ley_Cu,n.Ley_Cu),('FCu',a.FCu,n.FCu))v(campo,base,nuevo)
    UNION ALL
    SELECT 'Descarga vs nuevo',COALESCE(a.Flujo,n.Flujo),a.Flujo,n.Flujo,v.campo,v.base,v.nuevo
    FROM #validacion_m6_referencia a FULL JOIN #validacion_m6_nuevo n ON n.Flujo=a.Flujo
    CROSS APPLY (VALUES ('TMS_Inicial',a.TMS_Inicial,n.TMS_Inicial),('Ley_Cu_1',a.Ley_Cu_1,n.Ley_Cu_1),
        ('TMS_Final',a.TMS_Final,n.TMS_Final),('Ley_Cu_2',a.Ley_Cu_2,n.Ley_Cu_2),
        ('Tonelaje',a.Tonelaje,n.Tonelaje),('Ley_Cu',a.Ley_Cu,n.Ley_Cu),('FCu',a.FCu,n.FCu))v(campo,base,nuevo)
    WHERE @comparar_descarga=1
)
SELECT *,nuevo-base AS diferencia,
    CASE WHEN presente_base IS NULL OR presente_nuevo IS NULL THEN 1
         WHEN base IS NULL AND nuevo IS NULL THEN 0
         WHEN base IS NULL OR nuevo IS NULL THEN 1
         WHEN ABS(nuevo-base)>0.000001 THEN 1 ELSE 0 END AS difiere
INTO #validacion_m6_comparacion FROM comparaciones;

    IF @vista='resumen'
        SELECT @caso_id AS caso_id, @inicio AS fecha_inicio, @fin AS fecha_fin,
               c.comparacion,COUNT(r.campo) AS campos_comparados,
               CASE WHEN c.comparacion='Descarga vs nuevo' AND @comparar_descarga=0 THEN NULL
                    ELSE COALESCE(SUM(r.difiere),0) END AS diferencias,
               CASE WHEN c.comparacion='Descarga vs nuevo' AND @comparar_descarga=0
                    THEN 'OMITIDA: caso o fechas distintos a la descarga'
                    WHEN COALESCE(SUM(r.difiere),0)=0 THEN 'COINCIDEN'
                    ELSE 'REVISAR DIFERENCIAS' END AS estado
        FROM (VALUES ('Actual vs nuevo'),('Descarga vs nuevo'))c(comparacion)
        LEFT JOIN #validacion_m6_comparacion r ON r.comparacion=c.comparacion
        GROUP BY c.comparacion;
    ELSE IF @vista='diferencias'
        SELECT comparacion,Flujo,campo,base,nuevo,diferencia
        FROM #validacion_m6_comparacion WHERE difiere=1
        ORDER BY comparacion,TRY_CONVERT(int,SUBSTRING(Flujo,2,10)),campo;
    ELSE
        SELECT * FROM #validacion_m6_nuevo ORDER BY TRY_CONVERT(int,SUBSTRING(Flujo,2,10));
    END TRY
    BEGIN CATCH
        -- Entregar el error original como grilla, incluso si el cliente oculta Messages.
        SELECT 'ERROR: comparación no completada' AS estado,@caso_id AS caso_id,
               ERROR_NUMBER() AS numero_error, ERROR_PROCEDURE() AS procedimiento,
               ERROR_LINE() AS linea, ERROR_MESSAGE() AS detalle;
    END CATCH;
END;
